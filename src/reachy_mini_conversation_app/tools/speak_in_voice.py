import re
import wave
import asyncio
import logging
from typing import Any

import httpx

from reachy_mini_conversation_app.tools.core_tools import Tool, ToolDependencies
from reachy_mini_conversation_app.tools._space_audio import save_audio, wait_for_quiet, call_space_tool


logger = logging.getLogger(__name__)

VOICE_SPACE = "hugging-apps/firered-tts3"
_VOICE_MCP_URL = "https://hugging-apps-firered-tts3.hf.space/gradio_api/mcp/"
_VOICE_TOOL = "firered_tts3_voice_design"
# A line took 12 to 27 s; leave room for a ZeroGPU queue.
_GENERATION_TIMEOUT_S = 180.0
_MAX_TEXT_CHARS = 400
# The Space answers with a Gradio file record whose url points to the generated WAV.
_AUDIO_URL = re.compile(r"https://[^\s'\"]+\.(?:wav|mp3|flac|ogg)")
# Voice design reads other languages with English rules: French came out unintelligible (2026-11-23 ASR check).
SUPPORTED_LANGUAGES = ("en", "zh")


class SpeakInVoice(Tool):
    """Say a line in a voice described in words, generated by a voice-design Space."""

    name = "speak_in_voice"
    long_running = True
    description = (
        "Say a short line (a joke, a quote, a greeting) out loud in a special voice described in words, for "
        "example 'a very deep, slow, menacing villain voice with heavy breathing' or 'a squeaky, excited cartoon "
        "mouse'. If the user names a famous character or person, do not refuse: describe how that kind of voice "
        "sounds instead of naming them (a masked space villain: very deep, slow, menacing, breathing heavily). "
        "The voice only speaks English (or Chinese): if the conversation is in another language, first ask the "
        "user whether a line in English is fine, and call this tool only once they agree. "
        "It takes 15 to 30 seconds and runs in the background: tell the user you are warming up the voice and "
        "keep talking. The line plays by itself in the next pause. Nobody has heard it until its result "
        "arrives, so do not comment on it before then; afterwards react briefly."
    )
    parameters_schema = {
        "type": "object",
        "properties": {
            "text": {"type": "string", "description": "The line to say, one to three short sentences."},
            "voice": {
                "type": "string",
                "description": "The voice in words: pitch, pace, timbre, mood, accent, character.",
            },
            "language": {
                "type": "string",
                "description": "ISO 639-1 code of the line's language, e.g. en, fr. Only en and zh can be spoken.",
            },
        },
        "required": ["text", "voice", "language"],
    }

    async def __call__(self, deps: ToolDependencies, **kwargs: Any) -> dict[str, Any]:
        """Generate the line, play it, and return once it has been heard."""
        text = str(kwargs.get("text") or "").strip()
        voice = str(kwargs.get("voice") or "").strip()
        if not text or not voice:
            return {"error": "give both the line to say and a description of the voice"}
        if len(text) > _MAX_TEXT_CHARS:
            return {"error": f"the line is too long; keep it under {_MAX_TEXT_CHARS} characters"}
        language = str(kwargs.get("language") or "").strip().lower()
        if language not in SUPPORTED_LANGUAGES:
            # Refused before any Space call: a line in another language costs GPU time and comes out garbled.
            return {
                "error": f"the voice cannot speak {language or 'that language'}; it only speaks English or Chinese",
                "reason": "unsupported_language",
                "next": "Ask the user whether the line can be in English; if so, call again with an English line.",
            }

        logger.info("Tool call: speak_in_voice voice=%r text=%r", voice, text)
        result = await call_space_tool(
            VOICE_SPACE,
            _VOICE_MCP_URL,
            _VOICE_TOOL,
            {"instruction": voice, "text": text},
            timeout_s=_GENERATION_TIMEOUT_S,
        )
        if "error" in result:
            return result
        url = _AUDIO_URL.search(str(result.get("text") or ""))
        if url is None:
            logger.error("speak_in_voice: no audio in the Space result: %s", str(result.get("text"))[:300])
            return {"error": "the voice Space returned no audio"}
        try:
            path = await asyncio.to_thread(save_audio, url.group(0), "voice-line")
            with wave.open(str(path)) as clip:
                duration_s = clip.getnframes() / clip.getframerate()
        except (httpx.HTTPError, OSError, wave.Error) as exc:
            logger.error("speak_in_voice could not get the audio: %s", exc)
            return {"error": f"could not get the voice line: {exc}"}

        # The line is ready at a random moment; start it in a pause, not over anyone.
        await wait_for_quiet(deps)
        await asyncio.to_thread(deps.reachy_mini.media.play_sound, str(path))
        # Report only once the line has been heard, so the robot's reply does not talk over it.
        await asyncio.sleep(duration_s)
        return {
            "status": "played",
            "duration_s": round(duration_s, 1),
            "next": "The line was just played aloud in that voice; react briefly.",
        }
